// Crea una función de traducción t(clave, {parametros}) para un idioma dado.
export function makeT(lang) {
  const dict = T[lang] || T.fr;
  return (key, params) => {
    let s = dict[key] ?? T.fr[key] ?? key;
    if (params) {
      Object.keys(params).forEach((p) => {
        s = s.replace(new RegExp("\\{" + p + "\\}", "g"), params[p]);
      });
    }
    return s;
  };
}

export function getSavedLang() {
  return localStorage.getItem("ui_lang") || "fr";
}
